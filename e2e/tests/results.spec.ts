// Results, stats and exports in a real browser (M7).

test("results read back what respondents said, and export cleanly", async ({ page, browser }) => {
  const title = `E2E results ${Date.now()}`;
  const share = await createPublishedSurvey(page, title);

  // Two respondents answer, from their own contexts.
  for (const [text, choice] of [
    ["Setup took a while but support was quick.", "Weekly"],
    ["Loved it — nothing to change.", "Monthly"],
  ]) {
    const context = await browser.newContext({ storageState: undefined });
    const respondent = await context.newPage();
    await respondent.goto(share);
    await respondent.locator("textarea").fill(text);
    await respondent.getByRole("button", { name: "Next" }).click();
    await respondent.getByLabel(choice).check();
    await minFillWait(respondent);
    await respondent.getByRole("button", { name: "Submit answers" }).click();
    await expect(respondent.getByRole("heading", { name: "Thank you" })).toBeVisible();
    await context.close();
  }

  // The creator reads them.
  await page.getByRole("link", { name: /Results/ }).click();
  await expect(page.getByRole("heading", { name: "Results" })).toBeVisible();
  // The transcript list, specifically: the answers also appear in the
  // "All responses" table further down.
  const transcripts = page.locator(".transcript-text");
  await expect(transcripts.filter({ hasText: "Setup took a while" })).toBeVisible();
  await expect(transcripts.filter({ hasText: "Loved it" })).toBeVisible();

  // Stats are present and honest about what they mean.
  await expect(page.getByText("How this survey is going")).toBeVisible();
  await expect(page.getByText(/counts times the survey page was loaded/)).toBeVisible();

  // Small samples show no audience buckets at all (ADR-0009, n < 5).
  await expect(page.getByRole("heading", { name: "Audience" })).toHaveCount(0);

  // The results page is as accessible as the rest.
  const scan = await new AxeBuilder({ page }).analyze();
  expect(scan.violations).toEqual([]);

  // CSV downloads with both answers in it.
  const download = page.waitForEvent("download");
  await page.getByRole("link", { name: "Download CSV" }).click();
  const file = await download;
  const stream = await file.createReadStream();
  const csv = (await new Response(stream as any).text()) as string;
  expect(csv).toContain("response_id,version,submitted_at,duration_secs");
  expect(csv).toContain("Loved it");
});

test("an insight summary streams in and is labelled as AI output", async ({ page, browser }) => {
  // Two respondents, then a model reading their answers: past 30s.
  if (!scriptedAI) test.slow();

  const title = `E2E insights ${Date.now()}`;
  const share = await createPublishedSurvey(page, title);

  // Two answers to read.
  for (const text of ["Onboarding was confusing at first.", "Support fixed it in minutes."]) {
    const context = await browser.newContext({ storageState: undefined });
    const respondent = await context.newPage();
    await respondent.goto(share);
    await respondent.locator("textarea").fill(text);
    await respondent.getByRole("button", { name: "Next" }).click();
    await respondent.getByLabel("Weekly").check();
    await minFillWait(respondent);
    await respondent.getByRole("button", { name: "Submit answers" }).click();
    await context.close();
  }

  await page.getByRole("link", { name: /Results/ }).click();

  const offered = await offersInsights(page);
  if (!offered) {
    // No summary without a model — but the answers themselves, which are
    // the actual results, are all still there to read.
    await expect(page.locator(".transcript-text").first()).toBeVisible();
  }
  test.skip(!offered, "this instance has no AI configured, so it offers no Insight Summary");

  await page.getByRole("button", { name: "Analyse the responses" }).click();

  // The summary arrives, and the page reloads showing it with the label
  // that keeps analysis from passing for data.
  await expect(page.getByText(/AI-generated by/)).toBeVisible({ timeout: aiTimeout * 2 });
  await expect(page.getByText(/not the answers themselves/)).toBeVisible();
  await expect(page.locator(".insight-output")).not.toBeEmpty();
});

test("a workspace export can be built and downloaded", async ({ page }) => {
  await createPublishedSurvey(page, `E2E export ${Date.now()}`);

  await page.goto("/account");
  await page.getByRole("button", { name: /Export my workspace|Build a fresh export/ }).click();

  // The build is asynchronous; the page says so, and reloading shows the
  // finished archive.
  await expect(async () => {
    await page.reload();
    await expect(page.getByRole("link", { name: "Download the archive" })).toBeVisible({
      timeout: 1000,
    });
  }).toPass({ timeout: 30000 });

  // Fetched rather than clicked. The link carries the `download`
  // attribute, so Chromium hands it to its download manager, which does
  // not send the context's extra headers — against Basic-Auth-gated
  // staging that download 401s while every in-page request succeeds.
  // page.request shares the page's cookies and headers, so this asks the
  // same endpoint the same way the browser would, and then reads the
  // bytes: a stronger assertion than the suggested filename ever was.
  const href = await page.getByRole("link", { name: "Download the archive" }).getAttribute("href");
  expect(href).toBeTruthy();
  const archive = await page.request.get(href!);
  expect(archive.status()).toBe(200);
  expect(archive.headers()["content-type"]).toBe("application/zip");
  expect(archive.headers()["content-disposition"]).toContain(".zip");

  // "PK" is a zip's magic number: proof this is an archive, not an error
  // page with a hopeful content type.
  const bytes = await archive.body();
  expect(bytes.length).toBeGreaterThan(100);
  expect(bytes.subarray(0, 2).toString("latin1")).toBe("PK");
});
